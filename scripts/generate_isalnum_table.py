"""
Generate src/isalnum_table.rs: the code point ranges for which Python's
str.isalnum() is true.

Chunk IDs must stay identical to the ones the Python implementation produced,
and Rust's char::is_alphanumeric() disagrees with str.isalnum() on some
characters (e.g. combining marks), so the Rust side uses this table instead.

Run with the Python version in .python-version:
    uv run python scripts/generate_isalnum_table.py
"""

import sys
import unicodedata
from pathlib import Path

OUTPUT_FILE = Path(__file__).parent.parent / "src" / "isalnum_table.rs"


def get_isalnum_ranges():
    ranges = []
    start = None
    for code_point in range(sys.maxunicode + 2):
        is_alnum = code_point <= sys.maxunicode and chr(code_point).isalnum()
        if is_alnum and start is None:
            start = code_point
        elif not is_alnum and start is not None:
            ranges.append((start, code_point - 1))
            start = None
    return ranges


def render(ranges):
    version = unicodedata.unidata_version
    lines = [
        "// Generated by scripts/generate_isalnum_table.py. Do not edit.",
        f"// Python {sys.version.split()[0]}, Unicode {version}",
        "",
        f'pub const UNICODE_VERSION: &str = "{version}";',
        "",
        f"pub const ISALNUM_RANGES: [(u32, u32); {len(ranges)}] = [",
        *(f"    (0x{first:X}, 0x{last:X})," for first, last in ranges),
        "];",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUTPUT_FILE.write_text(render(get_isalnum_ranges()))
